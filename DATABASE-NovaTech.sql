-- create
CREATE TABLE ESCRITORIO (
  ESCRITORIO_Id INTEGER AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  uf VARCHAR(2) NOT NULL
);


CREATE TABLE DEPARTAMENTO (
  DEPARTAMENTO_Id INTEGER AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  sigla VARCHAR(10) NOT NULL
);


CREATE TABLE FUNCIONARIOS (
  FUNCIONARIOS_Id INTEGER AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  numero INT NOT NULL,
  cpf VARCHAR(14) NOT NULL,
  cargo VARCHAR(100)
);


CREATE TABLE PROJETOS (
  PROJETOS_Id INTEGER AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100),
  orcamento DECIMAL
);


CREATE TABLE CLIENTES (
  CLIENTES_Id INTEGER AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100),
  telefone VARCHAR(20)
);


-- Tabelas associativas (relacionamentos N:N)
CREATE TABLE ESCRITORIO_DEPARTAMENTO (
  ESCRITORIO_Id INTEGER NOT NULL,
  DEPARTAMENTO_Id INTEGER NOT NULL,
  PRIMARY KEY (ESCRITORIO_Id, DEPARTAMENTO_Id),
  FOREIGN KEY (ESCRITORIO_Id) REFERENCES ESCRITORIO(ESCRITORIO_Id) ON DELETE CASCADE,
  FOREIGN KEY (DEPARTAMENTO_Id) REFERENCES DEPARTAMENTO(DEPARTAMENTO_Id) ON DELETE CASCADE
);


CREATE TABLE DEPARTAMENTO_FUNCIONARIO (
  DEPARTAMENTO_Id INTEGER NOT NULL,
  FUNCIONARIOS_Id INTEGER NOT NULL,
  PRIMARY KEY (DEPARTAMENTO_Id, FUNCIONARIOS_Id),
  FOREIGN KEY (DEPARTAMENTO_Id) REFERENCES DEPARTAMENTO(DEPARTAMENTO_Id) ON DELETE CASCADE,
  FOREIGN KEY (FUNCIONARIOS_Id) REFERENCES FUNCIONARIOS(FUNCIONARIOS_Id) ON DELETE CASCADE
);


CREATE TABLE ESCRITORIO_PROJETO (
  ESCRITORIO_Id INTEGER NOT NULL,
  PROJETOS_Id INTEGER NOT NULL,
  PRIMARY KEY (ESCRITORIO_Id, PROJETOS_Id),
  FOREIGN KEY (ESCRITORIO_Id) REFERENCES ESCRITORIO(ESCRITORIO_Id) ON DELETE CASCADE,
  FOREIGN KEY (PROJETOS_Id) REFERENCES PROJETOS(PROJETOS_Id) ON DELETE CASCADE
);


CREATE TABLE PROJETO_CLIENTE (
  PROJETOS_Id INTEGER NOT NULL,
  CLIENTES_Id INTEGER NOT NULL,
  PRIMARY KEY (PROJETOS_Id, CLIENTES_Id),
  FOREIGN KEY (PROJETOS_Id) REFERENCES PROJETOS(PROJETOS_Id) ON DELETE CASCADE,
  FOREIGN KEY (CLIENTES_Id) REFERENCES CLIENTES(CLIENTES_Id) ON DELETE CASCADE
);


